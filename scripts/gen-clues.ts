/**
 * Generates 5 clues per rule (see src/lib/cluegen.ts).
 *   npm run gen-clues                 # print clues for rules that have none
 *   npm run gen-clues -- --write      # write src/rules/clues.ts (keeps existing clues)
 *   npm run gen-clues -- --write --all  # regenerate every rule
 *   npm run gen-clues -- --write num-even  # regenerate one rule
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RULES } from '../src/rules';
import { generateClues } from '../src/lib/cluegen';
import type { Clue } from '../src/rules/types';

const args = process.argv.slice(2);
const write = args.includes('--write');
const all = args.includes('--all');
const only = args.filter((a) => !a.startsWith('--'));

const out: Record<string, Clue[]> = {};
let failures = 0;
for (const rule of RULES) {
  const regen = all || only.includes(rule.id) || (!only.length && rule.clues.length !== 5);
  if (!regen) {
    out[rule.id] = rule.clues;
    continue;
  }
  const clues = generateClues(rule);
  if (!clues) {
    console.error(`✗ could not generate clues for ${rule.id}`);
    failures++;
    out[rule.id] = rule.clues;
    continue;
  }
  out[rule.id] = clues;
  console.log(`${rule.id}: ${clues.map((c) => `${JSON.stringify(c.item)} ${c.pass ? '✅' : '❌'}`).join('  ')}`);
}

if (write) {
  const body = Object.entries(out)
    .map(([id, clues]) => `  '${id}': [\n${clues.map((c) => `    { item: ${JSON.stringify(c.item)}, pass: ${c.pass} },`).join('\n')}\n  ],`)
    .join('\n');
  const file = `// Generated by \`npm run gen-clues -- --write\`. Safe to hand-edit; \`npm run validate-rules\` checks it.
import type { Clue } from './types';

export const CLUES: Record<string, Clue[]> = {
${body}
};
`;
  writeFileSync(join(process.cwd(), 'src', 'rules', 'clues.ts'), file);
  console.log('wrote src/rules/clues.ts');
}
process.exit(failures ? 1 : 0);
